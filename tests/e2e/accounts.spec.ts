 let requests=0;page.on('request',r=>{if(r.url().endsWith('/api/auth/register'))requests++;});
 await page.getByRole('button',{name:'계정 만들기',exact:true}).click();
 await expect(page.getByLabel('사용자 이름')).toBeFocused();
